export type SignedInCashAuthorityCoverage = {
  rows: readonly SignedInCashCoverageRow[];
  canonicalizedOperations: readonly string[];
  blockedOperations: readonly string[];
  nonBlockingLegacyOperations: readonly string[];
  criticalBlockers: readonly string[];
  criticalSignedInCashPathsTotal: number;
  criticalCanonicalizedCount: number;
  criticalBlockedCount: number;
  readiness: typeof SIGNED_IN_CASH_AUTHORITY_READINESS;
};

export function getSignedInCashAuthorityCoverage(): SignedInCashAuthorityCoverage {
  const auditIds = PRODUCTION_CASH_WRITE_AUDIT.map((row) => row.id);
  const rowIds = ROWS.map((row) => row.auditId);
  const missing = auditIds.filter((id) => !rowIds.includes(id));
  const extra = rowIds.filter((id) => !auditIds.includes(id));
  if (missing.length > 0 || extra.length > 0 || auditIds.length !== rowIds.length) {
    throw new Error('SIGNED_IN_CASH_COVERAGE_AUDIT_MISMATCH');
  }
  const canonicalizedOperations = ROWS.filter((row) => row.authorityStatus === 'CANONICAL_READY').map(
    (row) => row.auditId,
  );
  const blockedOperations = ROWS.filter((row) =>
    [
      'BLOCKED_SERVER_STATE',
      'BLOCKED_WORLD_STATE',
      'BLOCKED_VERIFICATION',
      'BLOCKED_LEGACY_ASSET',
    ].includes(row.authorityStatus),
  ).map((row) => row.auditId);
  const nonBlockingLegacyOperations = ROWS.filter(
    (row) => row.hudRole === 'CAN_REMAIN_LEGACY_LOCAL_ONLY',
  ).map((row) => row.auditId);
  const critical = ROWS.filter((row) => row.requiredBeforeCashAuthorityVersion1);
  const criticalCanonicalizedCount = critical.filter(
    (row) => row.authorityStatus === 'CANONICAL_READY',
  ).length;
  const criticalBlockedCount = critical.length - criticalCanonicalizedCount;
  return {
    rows: ROWS,
    canonicalizedOperations,
    blockedOperations,
    nonBlockingLegacyOperations,
    criticalBlockers: critical.map((row) => row.auditId),
    criticalSignedInCashPathsTotal: critical.length,
    criticalCanonicalizedCount,
    criticalBlockedCount,
    readiness: SIGNED_IN_CASH_AUTHORITY_READINESS,
  };
}
