export function formatCityUnlockRequirementRow(row: {
  type: 'PLAYER_LEVEL' | 'REPUTATION' | 'CASH' | 'WAREHOUSE_IN_CITY' | 'CITY_UNLOCKED';
  required: number | string;
  current: number | string;
}): { requiredLabel: string; currentLabel: string } {
  const copy = mapV2ExperienceCopy;
  if (row.type === 'PLAYER_LEVEL') {
    return {
      requiredLabel: `${copy.cityRequirementLevel} ${row.required}`,
      currentLabel: `${copy.cityCurrentPrefix}: ${row.current}`,
    };
  }
  if (row.type === 'REPUTATION') {
    return {
      requiredLabel: `${copy.cityRequirementReputation} ${row.required}`,
      currentLabel: `${copy.cityCurrentPrefix}: ${row.current}`,
    };
  }
  if (row.type === 'CASH') {
    const required = typeof row.required === 'number' ? row.required.toLocaleString('en-US') : row.required;
    const current = typeof row.current === 'number' ? row.current.toLocaleString('en-US') : row.current;
    return {
      requiredLabel: `${copy.cityRequirementCash} $${required}`,
      currentLabel: `${copy.cityCurrentPrefix}: $${current}`,
    };
  }
  if (row.type === 'WAREHOUSE_IN_CITY') {
    return {
      requiredLabel: `${copy.cityRequirementWarehouse}: ${row.required}`,
      currentLabel: `${copy.cityCurrentPrefix}: ${row.current === 'owned' ? copy.cityOwnedYes : copy.cityOwnedNo}`,
    };
  }
  return {
    requiredLabel: `${copy.cityRequirementCityOpen}: ${row.required}`,
    currentLabel: `${copy.cityCurrentPrefix}: ${row.current === 'open' ? copy.cityOpenYes : copy.cityOpenNo}`,
  };
}

